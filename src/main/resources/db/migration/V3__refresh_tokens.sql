-- Refresh tokens: long-lived, single-use, rotated on every refresh. Tokens issued from one login
-- share a family_id, so a reused (stolen) token can revoke the whole session.

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id   UUID         NOT NULL,
    -- SHA-256 of the token given to the client; the token itself is never stored.
    token_hash  VARCHAR(64)  NOT NULL,
    remember_me BOOLEAN      NOT NULL,
    expires_at  TIMESTAMPTZ  NOT NULL,
    -- Set when the token is exchanged; a second exchange means the token was stolen.
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_family_id ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_tokens_expires_at ON refresh_tokens (expires_at);
