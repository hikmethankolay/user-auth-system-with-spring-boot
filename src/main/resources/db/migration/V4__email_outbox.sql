-- Transactional outbox for emails: a message is stored in the same transaction as the change that
-- triggers it, then sent (and deleted) by the application, with retries while SMTP is unavailable.

CREATE TABLE email_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient       VARCHAR(254)  NOT NULL,
    subject         VARCHAR(200)  NOT NULL,
    body            TEXT          NOT NULL,
    attempts        INTEGER       NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ   NOT NULL,
    last_error      VARCHAR(500),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX ix_email_outbox_next_attempt_at ON email_outbox (next_attempt_at);
