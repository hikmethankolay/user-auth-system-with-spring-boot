-- Email verification flag and single-use tokens for email verification and password reset.

ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT false;

-- Accounts created before email verification existed are treated as verified,
-- so enabling verification does not lock existing users out.
UPDATE users SET email_verified = true;

CREATE TABLE account_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       VARCHAR(30)  NOT NULL,
    -- SHA-256 of the token sent by email; the token itself is never stored.
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_account_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_account_tokens_type CHECK (type IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET'))
);

CREATE INDEX ix_account_tokens_user_type ON account_tokens (user_id, type);
CREATE INDEX ix_account_tokens_expires_at ON account_tokens (expires_at);
