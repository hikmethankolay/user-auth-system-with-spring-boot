-- Sample feature (note/): a resource owned by a user. Copy it for your first feature, or delete the
-- package, its test and this migration before your first deployment.

CREATE TABLE notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Deleting the user deletes their notes.
    user_id    BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title      VARCHAR(200)   NOT NULL,
    body       VARCHAR(10000) NOT NULL,
    version    BIGINT         NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX ix_notes_user_id ON notes (user_id);
