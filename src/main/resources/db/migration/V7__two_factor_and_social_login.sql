-- Two-factor authentication (TOTP) and social login (GitHub, Google).

-- The TOTP secret, encrypted with AES-GCM under MFA_ENCRYPTION_KEY; set at enrollment, kept only while
-- totp_enabled is true or an enrollment is pending.
ALTER TABLE users ADD COLUMN totp_secret VARCHAR(100);
ALTER TABLE users ADD COLUMN totp_enabled BOOLEAN NOT NULL DEFAULT false;
-- The last accepted 30-second time step, so a code cannot be used twice.
ALTER TABLE users ADD COLUMN totp_last_step BIGINT NOT NULL DEFAULT 0;

-- Single-use codes for when the authenticator is lost. Only SHA-256 hashes are stored.
-- The unique constraint's index also serves lookups by user_id.
CREATE TABLE recovery_codes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_hash  VARCHAR(64) NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_recovery_codes_user_hash UNIQUE (user_id, code_hash)
);

-- Accounts at an external provider linked to a user: the provider's stable user id, never the email,
-- which the user can change at the provider.
CREATE TABLE social_identities (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider   VARCHAR(20)  NOT NULL,
    subject    VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_social_identities_provider_subject UNIQUE (provider, subject)
);

CREATE INDEX ix_social_identities_user_id ON social_identities (user_id);
